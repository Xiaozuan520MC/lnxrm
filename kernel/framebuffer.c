/* extended palette: colors 16..255 = 6x6x6 RGB cube + 24 greys */
static void fb_setup_palette(void)
{
    /* program the first 16 entries via VGA DAC */
    outb(0x3C8, 0);
    for (int i = 0; i < 16; i++) {
        outb(0x3C9, palette16[i][0] >> 2);
        outb(0x3C9, palette16[i][1] >> 2);
        outb(0x3C9, palette16[i][2] >> 2);
    }
    /* 6x6x6 colour cube: indices 16..231 */
    outb(0x3C8, 16);
    for (int r = 0; r < 6; r++)
        for (int g = 0; g < 6; g++)
            for (int b = 0; b < 6; b++) {
                outb(0x3C9, r ? (r * 40 + 55) : 0);
                outb(0x3C9, g ? (g * 40 + 55) : 0);
                outb(0x3C9, b ? (b * 40 + 55) : 0);
            }
    /* 24 greys: indices 232..255 */
    outb(0x3C8, 232);
    for (int i = 0; i < 24; i++) {
        u8 v = (u8)(8 + i * 10);
        outb(0x3C9, v >> 2);
        outb(0x3C9, v >> 2);
        outb(0x3C9, v >> 2);
    }
}

/* ---- public API ---- */

/* Bochs/VBE DISPI I/O ports for mode switching from protected mode. */
#define DISPI_INDEX  0x1CE
#define DISPI_DATA   0x1CF

static void dispi_write(u16 idx, u16 val)
{
    outw(DISPI_INDEX, idx);
    outw(DISPI_DATA, val);
}

static void vbe_set_mode(void)
{
    /* Disable VBE before changing mode parameters */
    dispi_write(4, 0);
    dispi_write(1, FB_WIDTH);      /* X resolution */
    dispi_write(2, FB_HEIGHT);     /* Y resolution */
    dispi_write(3, FB_BPP);        /* bits per pixel */
    /* Enable VBE (bit 0) + LFB (bit 1) */
    dispi_write(4, 0x03);
}

/* ---- framebuffer text console ---- */
#define FBC_COLS  (FB_WIDTH / 8)   /* 80 */
#define FBC_ROWS  (FB_HEIGHT / 16) /* 30 */

int fb_active = 0;
static int fbc_row, fbc_col;
static u8  fbc_fg = FB_CLR_LGREY;
static u8  fbc_bg = FB_CLR_BLACK;

/* ANSI escape state machine */
static int fbc_esc = 0;
static char fbc_esc_buf[8];
static int  fbc_esc_len = 0;

static u8 fbc_ansi_color(u8 code)
{
    static const u8 map[] = { 0, 4, 2, 6, 1, 5, 3, 7 };
    return map[code - 30];
}

static void fbc_cursor(int show)
{
    if (!fb_ptr) return;
    u8 c = show ? FB_CLR_LGREY : fbc_bg;
    for (int dy = 14; dy < 16; dy++)
        for (int dx = 0; dx < 8; dx++)
            fb_put_pixel(fbc_col * 8 + dx, fbc_row * 16 + dy, c);
}

static void fbc_esc_process(void)
{
    char last = fbc_esc_buf[fbc_esc_len - 1];
    if (last == 'J') {
        if (fbc_esc_len >= 2 && fbc_esc_buf[0] == '2') {
            fb_clear(fbc_bg);
            fbc_row = fbc_col = 0;
        }
    } else if (last == 'H') {
        int row = 1, col = 1, num = 0, have = 0;
        for (int i = 0; i < fbc_esc_len - 1; i++) {
            if (fbc_esc_buf[i] >= '0' && fbc_esc_buf[i] <= '9') {
                num = num * 10 + (fbc_esc_buf[i] - '0');
                have = 1;
            } else if (fbc_esc_buf[i] == ';') {
                if (have) { row = num; num = 0; have = 0; }
            }
        }
        if (have) col = num;
        fbc_row = row - 1;
        fbc_col = col - 1;
        if (fbc_row < 0) fbc_row = 0;
        if (fbc_row >= FBC_ROWS) fbc_row = FBC_ROWS - 1;
        if (fbc_col < 0) fbc_col = 0;
        if (fbc_col >= FBC_COLS) fbc_col = FBC_COLS - 1;
    } else if (last == 'm') {
        int num = 0, have = 0;
        for (int i = 0; i < fbc_esc_len; i++) {
            if (fbc_esc_buf[i] >= '0' && fbc_esc_buf[i] <= '9') {
                num = num * 10 + (fbc_esc_buf[i] - '0');
                have = 1;
            } else if (fbc_esc_buf[i] == ';' || i == fbc_esc_len - 1) {
                if (have) {
                    if (num == 0) { fbc_fg = FB_CLR_LGREY; fbc_bg = FB_CLR_BLACK; }
                    else if (num >= 30 && num <= 37) fbc_fg = fbc_ansi_color(num);
                    else if (num >= 40 && num <= 47) fbc_bg = fbc_ansi_color(num - 10);
                    else if (num == 1) fbc_fg = FB_CLR_WHITE;
                    num = 0; have = 0;
                }
            }
        }
    }
}

static void fbc_scroll(void)
{
    u32 row_bytes = fb_pitch * 16;
    for (int r = 0; r < FBC_ROWS - 1; r++) {
        memcpy((void *)(FB_VMA + r * row_bytes),
               (void *)(FB_VMA + (r + 1) * row_bytes),
               row_bytes);
    }
    memset((void *)(FB_VMA + (FBC_ROWS - 1) * row_bytes),
           fbc_bg, row_bytes);
}

void fb_console_putc(char c)
{
    if (!fb_active) return;

    if (fbc_esc == 0 && c == '\033') { fbc_esc = 1; return; }
    if (fbc_esc == 1) {
        if (c == '[') { fbc_esc = 2; fbc_esc_len = 0; }
        else fbc_esc = 0;
        return;
    }
    if (fbc_esc == 2) {
        if (fbc_esc_len < (int)sizeof(fbc_esc_buf) - 1)
            fbc_esc_buf[fbc_esc_len++] = c;
        if ((c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z')) {
            fbc_esc_buf[fbc_esc_len] = 0;
            fbc_esc_process();
            fbc_esc = 0;
        }
        return;
    }

    fbc_cursor(0);

    switch (c) {
    case '\n':
        fbc_col = 0;
        if (++fbc_row >= FBC_ROWS) { fbc_scroll(); fbc_row--; }
        break;
    case '\r':
        break;
    case '\b':
        if (fbc_col > 0) {
            fbc_col--;
            fb_draw_char(fbc_col * 8, fbc_row * 16, ' ', fbc_fg, fbc_bg);
        }
        break;
    default:
        if (c >= 0x20 && c <= 0x7E) {
            fb_draw_char(fbc_col * 8, fbc_row * 16, c, fbc_fg, fbc_bg);
            if (++fbc_col >= FBC_COLS) {
                fbc_col = 0;
                if (++fbc_row >= FBC_ROWS) { fbc_scroll(); fbc_row--; }
            }
        }
    }

    fbc_cursor(1);
}

void fb_console_init(void)
{
    fbc_row = fbc_col = 0;
    fb_clear(fbc_bg);
    fb_active = 1;

    int n = ring_get_count();
    for (int i = 0; i < n; i++)
        fb_console_putc(ring_get_char(i));
}

void fb_init(void)
{
    struct fb_info *fb = &bootinfo.fb;
    if (!fb->ok || !fb->phys_addr)
        return;

    /* Switch VGA from text mode to VBE graphics mode via DISPI I/O ports.
     * This must happen here, not in setup.asm, so that boot messages
     * remain visible in VGA text mode during early kernel startup. */
    vbe_set_mode();

    /* Map the framebuffer into kernel VA using 4 KiB pages. */
    u64 pa = fb->phys_addr;
    u32 size = fb->pitch * fb->height;
    for (u32 off = 0; off < size; off += PAGE_SIZE) {
        vmm_map_kernel_page(FB_VMA + off, pa + off, PG_PCD);
    }

    fb_ptr = (volatile u8 *)FB_VMA;
    fb_pitch = fb->pitch;

    kprintf("[fb] mapped at %p (phys=0x%x), pitch=%d\n",
            (void *)fb_ptr, (u32)pa, fb_pitch);

    /* Set up the VGA DAC palette for 256-colour mode */
    fb_setup_palette();

    /* Switch console to framebuffer output */
    fb_console_init();
}

void fb_put_pixel(u32 x, u32 y, u8 color)
{
    if (x >= FB_WIDTH || y >= FB_HEIGHT || !fb_ptr)
        return;
    fb_ptr[y * fb_pitch + x] = color;
}

void fb_clear(u8 color)
{
    if (!fb_ptr) return;
    memset((void *)fb_ptr, color, fb_pitch * FB_HEIGHT);
}

void fb_fill_rect(u32 x, u32 y, u32 w, u32 h, u8 color)
{
    if (!fb_ptr) return;
    for (u32 row = y; row < y + h && row < FB_HEIGHT; row++)
        for (u32 col = x; col < x + w && col < FB_WIDTH; col++)
            fb_ptr[row * fb_pitch + col] = color;
}

void fb_draw_char(u32 x, u32 y, char ch, u8 fg, u8 bg)
{
    if (!fb_ptr) return;
    int idx = (u8)ch - 0x20;
    if (idx < 0 || idx > 94) idx = 0; /* blank for unprintable */

    const u8 *glyph = font8x16[idx];
    for (int row = 0; row < 16; row++) {
        u8 bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            u8 c = (bits & (0x80 >> col)) ? fg : bg;
            fb_put_pixel(x + col, y + row, c);
        }
    }
}

void fb_puts(u32 x, u32 y, const char *s, u8 fg, u8 bg)
{
    while (*s) {
        fb_draw_char(x, y, *s, fg, bg);
        x += 8;
        s++;
    }
}

void fb_show_demo(void)
{
    if (!fb_ptr) return;

    fb_clear(FB_CLR_BLACK);

    /* colour bar across the top — small blocks */
    for (u32 i = 0; i < 16; i++)
        fb_fill_rect(i * 10, 0, 10, 10, (u8)i);

    /* 6x6x6 cube — compact, top-left corner */
    for (int r = 0; r < 6; r++)
        for (int g = 0; g < 6; g++)
            for (int b = 0; b < 6; b++)
                fb_fill_rect(10 + b * 10, 12 + r * 10, 9, 9,
                             (u8)(16 + r * 36 + g * 6 + b));

    /* title text */
    fb_puts(10, 80, "lnxrm 640x480 256c VBE", FB_CLR_LGREEN, FB_CLR_BLACK);
    fb_puts(10, 96, "framebuffer ready", FB_CLR_LCYAN, FB_CLR_BLACK);
}
